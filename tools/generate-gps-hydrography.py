"""Offline generation, Shapely 2.1.2. Run from repository root.
Source extracts are checked in. No hand-drawn or interpolated river connection.
"""
import json, math
from pathlib import Path
from shapely.geometry import shape, mapping, box, LineString, Point
from shapely.ops import unary_union, split, nearest_points
ROOT=Path('assets/maps/hydrography')
geo=json.loads(Path('gps-geography.js').read_text().split('const data=',1)[1].split(';if(',1)[0])
p=geo['projection']
def project(c):
 x,y=c
 return [round(p['dx']+(x*p['cos']-p['xmin'])*p['scale'],3),round(p['dy']+(p['ymax']-y)*p['scale'],3)]
def lines(g):
 if g.is_empty:return []
 if g.geom_type=='LineString':return [list(map(list,g.coords))]
 return [a for part in g.geoms for a in lines(part)]
def polygons(g):
 if g.is_empty:return []
 if g.geom_type=='Polygon':return [[list(map(list,r.coords)) for r in [g.exterior,*g.interiors]]]
 return [a for part in g.geoms for a in polygons(part)]
def linepath(ls):return ' '.join('M'+'L'.join(','.join(map(str,project(c))) for c in line) for line in ls)

def polypath(ps):return ' '.join(linepath([r])+'Z' for poly in ps for r in poly)
source=json.loads((ROOT/'rivers.geojson').read_text())['features']
water=shape(json.loads((ROOT/'coastal-water.geojson').read_text())['features'][0]['geometry'])
# The peninsula tip is an actual vertex of Natural Earth's shoreline.
bec=[-0.596181,45.024644]
assert any(list(c)==bec for c in water.exterior.coords)
# Mouth section uses two existing shoreline vertices, not a constructed shoreline.
mouth=[[-1.069163,45.57331],[-0.98351,45.586982]]
a,b=mouth;vx,vy=b[0]-a[0],b[1]-a[1]
cut=LineString([(a[0]-vx*20,a[1]-vy*20),(a[0]+vx*20,a[1]+vy*20)])
inlet=next(g for g in split(water,cut).geoms if g.covers(Point(bec)))
upper=inlet.intersection(box(-1.3,44.8,-.3,bec[1]))
garonne=next(g for g in upper.geoms if g.covers(Point(-.55,44.92)))
dordogne=next(g for g in upper.geoms if g.covers(Point(-.54,45.025-0.002)))
estuary=inlet.intersection(box(-1.3,bec[1],-.3,45.7))
france=unary_union([shape(f['geometry']) for f in json.loads(Path('assets/maps/regions-france.geojson').read_text())['features'] if int(f['properties']['code'])>10])
river_data=[]
for id,name,names,anchor in [('a','Seine',['Seine'],[1.15,49.1]),('b','Rhin',['Rhin','Rhine'],[7.85,48.4]),('c','Garonne',['Garonne'],[.6,44.3]),('d','Dordogne',['Dordogne'],[.5,44.85]),('e','Loire',['Loire'],[1,47.7]),('f','Rhône',['Rhône'],[4.8,45])]:
 g=unary_union([shape(f['geometry']) for f in source if f['properties']['name'] in names])
 if id=='b':g=g.intersection(box(6.5,47.5,8.5,49.05))
 if id=='f':g=g.intersection(france.buffer(.01))
 ls=lines(g)
 waters=polygons(garonne if id=='c' else dordogne) if id in ['c','d'] else []
 old=next((r for r in geo['rivers'] if r['id']==id),None)
 river_data.append(dict(id=id,name=name,lines=ls,path=linepath(ls),anchor=old['anchor'] if old else project(nearest_points(g,Point(anchor))[0].coords[0]),waterPolygons=waters,waterPath=polypath(waters)))
# Independent generalized NE layers: require a subpixel junction gap (<0.001°).
assert water.is_valid and estuary.is_valid
for point in mouth:assert any(list(c)==point for c in water.exterior.coords)
assert estuary.intersection(garonne).area<1e-12
assert estuary.intersection(dordogne).area<1e-12
for id,w in [('c',garonne),('d',dordogne)]:
 r=next(r for r in river_data if r['id']==id)
 distance=min(Point(c).distance(w) for line in r['lines'] for c in [line[0],line[-1]])
 print(id, 'line-to-water gap (degrees):',distance)
 assert distance<.001
 assert w.distance(estuary)<1e-8
marine=shape(json.loads((ROOT/'marine-context.geojson').read_text())['features'][0]['geometry'])
data=dict(rivers=river_data,estuary=dict(id='gironde',name='Estuaire de la Gironde',polygons=polygons(estuary),path=polypath(polygons(estuary))),oceanPath=polypath(polygons(marine)),coastalWater=polygons(water),confluence=dict(coordinates=bec,position=project(bec)),mouth=mouth,tolerance=12)
Path('gps-hydrography.js').write_text('/* Generated by tools/generate-gps-hydrography.py. Natural Earth 1:10m, public domain. */\n(function(root){const data='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';if(typeof module!=="undefined"&&module.exports)module.exports=data;else root.GpsHydrography=data;})(globalThis);\n')
